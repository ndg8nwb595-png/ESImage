"""9 号 §3.1 错误码总表（单一来源）。

后端所有模块的错误码与 HTTP 状态映射都应引用本表，避免各 demo 各自维护一份。
`30012` 原用于「模板与图片角色不匹配」，模板改为整套模板后废弃，编号保留不复用。
"""

from __future__ import annotations

# code -> (http_status, message)
ERROR_CODES: dict[int, tuple[int, str]] = {
    0: (200, "ok"),
    # 参数错误（HTTP 400）
    10001: (400, "参数错误"),
    10002: (400, "缺少必填参数"),
    10003: (400, "参数格式错误"),
    10004: (400, "参数超出范围"),
    # 鉴权失败（HTTP 401/403）
    20001: (401, "用户名或密码错误"),
    20002: (401, "登录已过期"),
    20003: (401, "token 无效"),
    20004: (403, "账号不可用"),
    20005: (403, "无权限"),
    20006: (403, "无权操作超管账号"),
    20007: (403, "不能操作自己"),
    # 业务错误（HTTP 400/404/409）
    30001: (400, "模型调用失败"),
    30002: (400, "模型未配置"),
    30003: (409, "已有生成任务进行中"),
    30004: (404, "批次不存在"),
    30005: (409, "批次状态不允许该操作"),
    30006: (400, "上传文件不符合要求"),
    30007: (400, "内容未通过审核"),
    30008: (409, "已有导出任务进行中"),
    30009: (409, "角色组合不合法"),
    30010: (409, "用户名已存在"),
    30011: (409, "必须保留至少一个可用超管"),
    30013: (404, "会话不存在"),
    30014: (404, "文件不存在或归档不可用"),
    30015: (409, "权限点不可授予该角色"),
    30016: (404, "模板/素材/尺寸不存在"),
    # 系统错误（HTTP 500）
    50001: (500, "系统内部错误"),
    50002: (500, "数据库错误"),
    50003: (500, "存储服务错误"),
}


def http_status_of(code: int) -> int:
    """返回错误码对应的 HTTP 状态码；未知码按 400 处理。"""
    return ERROR_CODES.get(code, (400, "未知错误"))[0]


def message_of(code: int) -> str:
    """返回错误码对应的默认文案。"""
    return ERROR_CODES.get(code, (400, "未知错误"))[1]


def error_code_table() -> list[dict]:
    """OpenAPI 用：把总表转成可序列化的列表。"""
    return [
        {"code": code, "http_status": status, "message": message}
        for code, (status, message) in sorted(ERROR_CODES.items())
    ]
